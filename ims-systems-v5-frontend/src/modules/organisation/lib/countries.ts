export const DEFAULT_COUNTRY: OrganisationCountryOption =
  ORGANISATION_COUNTRIES.find((c) => c.code === "GB") ??
  ORGANISATION_COUNTRIES[0]!;

export function findOrganisationCountry(
  codeOrName: string
): OrganisationCountryOption | undefined {
  const key = codeOrName.trim().toLowerCase();
  if (!key) return undefined;
  return ORGANISATION_COUNTRIES.find(
    (c) => c.code.toLowerCase() === key || c.name.toLowerCase() === key
  );
}
