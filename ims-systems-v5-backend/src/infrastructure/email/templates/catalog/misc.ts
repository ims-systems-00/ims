export function renderNotification(data: {
  title: string;
  body: string;
  actionUrl?: string;
  actionLabel?: string;
}): RenderedEmail {
  return renderEmailLayout(data.title, {
    mode: "action",
    eyebrow: "Notification",
    title: data.title,
    paragraphs: [data.body],
    ...(data.actionUrl
      ? {
          cta: {
            label: data.actionLabel?.trim() || "Open in iMS",
            href: data.actionUrl,
          },
        }
      : {}),
  });
}

export function renderCampaignWrap(data: {
  subject: string;
  bodyHtml: string;
}): RenderedEmail {
  const escapedSubject = data.subject;
  return renderEmailLayout(escapedSubject, {
    mode: "default",
    eyebrow: "Message",
    title: escapedSubject,
    safeHtmlBlock: data.bodyHtml,
    preheader: escapedSubject,
  });
}

export function renderGoLiveOnboardSuccess(data: {
  paymentType: string;
  superUser: number;
  users: number;
  groups: number;
  complianceTools: string[];
}): RenderedEmail {
  return renderEmailLayout("Welcome to iMS — your workspace is live", {
    mode: "success",
    eyebrow: "Go live",
    statusChip: { label: "Activated", tone: "success" },
    title: "Your organisation is live",
    hero: "Welcome aboard — your adoption pack is attached.",
    paragraphs: [
      "Congratulations — your iMS workspace is active. Use the attached adoption pack and service charter to get your team started.",
    ],
    meta: [
      { label: "Payment", value: data.paymentType },
      { label: "Super users", value: String(data.superUser) },
      { label: "Users", value: String(data.users) },
      { label: "Groups", value: String(data.groups) },
      {
        label: "Compliance tools",
        value:
          data.complianceTools.length > 0
            ? data.complianceTools.join(", ")
            : "None",
      },
    ],
    attachmentNote: "Adoption pack and service charter attached when available.",
  });
}

