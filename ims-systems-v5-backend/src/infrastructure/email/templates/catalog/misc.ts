import { renderEmailLayout } from "../layout";
import type { RenderedEmail } from "../types";

export function renderPartnershipApplicationReceived(data: {
  organisationName: string;
}): RenderedEmail {
  return renderEmailLayout("Welcome to the iMS Partnership programme", {
    mode: "success",
    eyebrow: "Partnership",
    statusChip: { label: "Application received", tone: "success" },
    title: "Thanks for applying",
    paragraphs: [
      `We received the partnership application for ${data.organisationName}.`,
      "Our partnerships team will review it and follow up with next steps.",
    ],
    meta: [{ label: "Organisation", value: data.organisationName }],
  });
}

export function renderPartnershipCodeReady(data: {
  organisationName: string;
  partnerCode: string;
  htmlExtra?: string;
}): RenderedEmail {
  return renderEmailLayout("Your iMS partner code is ready", {
    mode: "success",
    eyebrow: "Partnership",
    statusChip: { label: "Code ready", tone: "success" },
    title: "Your partner code",
    paragraphs: [
      `Great news — the partner code for ${data.organisationName} is ready to use.`,
    ],
    codeBlock: { label: "Partner code", value: data.partnerCode },
    meta: [{ label: "Organisation", value: data.organisationName }],
    ...(data.htmlExtra ? { safeHtmlBlock: data.htmlExtra } : {}),
  });
}

export function renderInvoice(data: {
  recipientName: string;
  reference: string;
  customerName: string;
  totalLabel: string;
  dueDateLabel: string;
}): RenderedEmail {
  return renderEmailLayout(`Invoice ${data.reference} from iMS Systems`, {
    mode: "receipt",
    eyebrow: "Invoice",
    statusChip: { label: "Ready", tone: "info" },
    title: `Invoice ${data.reference}`,
    greeting: `Hi ${data.recipientName},`,
    paragraphs: [
      `Please find invoice ${data.reference} for ${data.customerName}.`,
      "A PDF copy is attached when available.",
    ],
    meta: [
      { label: "Reference", value: data.reference },
      { label: "Customer", value: data.customerName },
      { label: "Total", value: data.totalLabel },
      { label: "Due", value: data.dueDateLabel },
    ],
    attachmentNote: "Invoice PDF attached when generated by the billing system.",
  });
}

