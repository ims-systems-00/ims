/**
 * Real AuditReportPort (N-14) — builds an audit extract report
 * (summary, identifications, embedded risks, OFIs) and delivers it
 * to the recipient via the shared EmailSystem, with the full report
 * HTML plus any cloud-stored audit attachments.
 */

import {
  renderEmailForOrganisation,
  type EmailBranding,
} from "../../../infrastructure/email/templates";
import type { EmailAttachment } from "../../../infrastructure/email";
import type { EmailSystem } from "../../../infrastructure/queue";
import { getLocalObjectStorage } from "../../files/local-fallback-storage";
import type { ObjectStoragePort } from "../../files/ports";
import type { Audit, AuditAttachment } from "../types";
import { NoOpAuditReportAdapter, type AuditReportPort } from "../ports";

/** Soft cap so report emails stay within provider size limits. */
const MAX_ATTACHMENT_BYTES = 8 * 1024 * 1024;
const MAX_TOTAL_ATTACHMENT_BYTES = 20 * 1024 * 1024;

function esc(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function fmtDate(value: Date | string): string {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime())
    ? String(value)
    : date.toLocaleDateString("en-GB", { dateStyle: "medium" });
}

export function buildAuditReportHtml(audit: Audit): string {
  const identifications = audit.identifications.length
    ? `<ul>${audit.identifications
        .map(
          (item) =>
            `<li><strong>${esc(item.nonConformity)}</strong>${
              item.rootCause ? ` — Root cause: ${esc(item.rootCause)}` : ""
            }</li>`
        )
        .join("")}</ul>`
    : "<p>None recorded.</p>";

  const risks = audit.risks.length
    ? `<ul>${audit.risks
        .map(
          (risk) =>
            `<li><strong>${esc(risk.title)}</strong> (score ${risk.total}) — ${esc(risk.description)}</li>`
        )
        .join("")}</ul>`
    : "<p>None recorded.</p>";

  const ofis = audit.ofis.length
    ? `<ul>${audit.ofis
        .map(
          (ofi) =>
            `<li><strong>${esc(ofi.title)}</strong> — ${esc(ofi.opportunityForImprovement)}</li>`
        )
        .join("")}</ul>`
    : "<p>None recorded.</p>";

  const attachments = audit.attachments.length
    ? `<ul>${audit.attachments
        .map((file) => `<li>${esc(file.fileName)}</li>`)
        .join("")}</ul>`
    : "<p>None attached.</p>";

  return `<!doctype html>
<html><head><meta charset="utf-8"><title>Audit report ${esc(audit.reference)}</title></head>
<body>
<h1>Audit report — ${esc(audit.reference)}: ${esc(audit.title)}</h1>
<table>
<tr><th align="left">Type</th><td>${esc(audit.type)}</td></tr>
<tr><th align="left">Focus area</th><td>${esc(audit.focusArea)}</td></tr>
<tr><th align="left">Start date</th><td>${fmtDate(audit.startDate)}${audit.time ? ` ${esc(audit.time)}` : ""}</td></tr>
<tr><th align="left">Interval</th><td>${esc(audit.interval)}</td></tr>
<tr><th align="left">Status</th><td>${audit.completed?.status ? "Completed" : "Open"}</td></tr>
${audit.comment ? `<tr><th align="left">Comment</th><td>${esc(audit.comment)}</td></tr>` : ""}
</table>
<h2>Identifications / non-conformities (${audit.identifications.length})</h2>
${identifications}
<h2>Embedded risks (${audit.risks.length})</h2>
${risks}
<h2>Opportunities for improvement (${audit.ofis.length})</h2>
${ofis}
<h2>Attachments (${audit.attachments.length})</h2>
${attachments}
<p>Generated by iMS Systems on ${fmtDate(new Date())}.</p>
</body></html>`;
}

type ReadableStorage = ObjectStoragePort & {
  readObject?: (input: { bucket: string; key: string }) => Promise<Buffer>;
};

async function loadStoredBytes(
  storage: ObjectStoragePort,
  bucket: string,
  key: string
): Promise<Buffer | null> {
  const withRead = storage as ReadableStorage;
  if (typeof withRead.readObject === "function") {
    try {
      return await withRead.readObject({ bucket, key });
    } catch {
      // Non-local buckets may not support direct reads — fall through.
    }
  }

  const local = getLocalObjectStorage(storage);
  if (local) {
    try {
      return await local.readObject({ bucket, key });
    } catch {
      // Object lives in remote storage.
    }
  }

  try {
    const url = await storage.createViewUrl({
      bucket,
      key,
      expiresInSeconds: 300,
      disposition: "attachment",
    });
    if (!url || url.startsWith("memory://")) return null;
    const response = await fetch(url);
    if (!response.ok) return null;
    return Buffer.from(await response.arrayBuffer());
  } catch {
    return null;
  }
}

async function buildFileAttachments(
  audit: Audit,
  storage: ObjectStoragePort | undefined
): Promise<EmailAttachment[]> {
  if (!storage || audit.attachments.length === 0) return [];

  const out: EmailAttachment[] = [];
  let totalBytes = 0;

  for (const file of audit.attachments) {
    const loaded = await loadAuditAttachment(storage, file);
    if (!loaded) continue;
    if (loaded.byteLength > MAX_ATTACHMENT_BYTES) continue;
    if (totalBytes + loaded.byteLength > MAX_TOTAL_ATTACHMENT_BYTES) break;

    out.push({
      filename: file.fileName || "attachment",
      contentBase64: loaded.toString("base64"),
      type: file.mimeType || "application/octet-stream",
      disposition: "attachment",
    });
    totalBytes += loaded.byteLength;
  }

  return out;
}

async function loadAuditAttachment(
  storage: ObjectStoragePort,
  file: AuditAttachment
): Promise<Buffer | null> {
  if (file.bucket && file.storageKey) {
    const fromStorage = await loadStoredBytes(
      storage,
      file.bucket,
      file.storageKey
    );
    if (fromStorage) return fromStorage;
  }

  if (file.url) {
    try {
      const response = await fetch(file.url);
      if (!response.ok) return null;
      return Buffer.from(await response.arrayBuffer());
    } catch {
      return null;
    }
  }

  return null;
}

export type CreateAuditReportAdapterOptions = {
  resolveEmailBranding?: (
    organizationId: string
  ) => Promise<EmailBranding>;
  storage?: ObjectStoragePort;
};

export function createAuditReportAdapter(
  email: EmailSystem | undefined,
  resolveEmailBrandingOrOptions?:
    | ((organizationId: string) => Promise<EmailBranding>)
    | CreateAuditReportAdapterOptions,
  maybeOptions?: CreateAuditReportAdapterOptions
): AuditReportPort {
  const options: CreateAuditReportAdapterOptions =
    typeof resolveEmailBrandingOrOptions === "function"
      ? {
          resolveEmailBranding: resolveEmailBrandingOrOptions,
          ...(maybeOptions ?? {}),
        }
      : (resolveEmailBrandingOrOptions ?? {});

  if (!email) return new NoOpAuditReportAdapter();

  const { resolveEmailBranding, storage } = options;

  return {
    async enqueueExtractReport({
      audit,
      recipientName,
      recipientEmail,
      organizationId,
    }) {
      const summaryHtml = buildAuditReportHtml(audit);
      const rendered = await renderEmailForOrganisation(
        "audit-report",
        {
          recipientName,
          reference: audit.reference,
          title: audit.title,
          summaryHtml,
        },
        { organizationId, resolveBranding: resolveEmailBranding }
      );

      const fileAttachments = await buildFileAttachments(audit, storage);

      await email.sendTransactional({
        to: recipientEmail,
        subject: rendered.subject,
        html: rendered.html,
        text: rendered.text,
        category: "transactional",
        organizationId,
        attachments: [
          {
            filename: `audit-report-${audit.reference}.html`,
            contentBase64: Buffer.from(summaryHtml, "utf8").toString("base64"),
            type: "text/html",
          },
          ...fileAttachments,
        ],
      });
    },
  };
}
